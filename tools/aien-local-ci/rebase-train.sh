#!/usr/bin/env bash
# rebase-train.sh: keep ready-to-merge pull requests on top of their base branch (Spark pipeline, runs before
# `pipeline.sh round`).
#
#   rebase-train.sh [--dry-run] [--repos a,b] [--pr N]      (--pr: only that pull request number, for a trial run)
#
# For every repo, every open, non-draft pull request labeled exactly ready-to-merge whose head branch lives in the
# same repository (not a fork) and that GitHub reports CONFLICTING or BEHIND:
#   1. fetch pull/N/head into a temporary ref of the trusted clone, check it out in a scratch worktree;
#   2. skip it when its head commit is younger than 10 minutes (committer time) or when it touches a trust-surface
#      file (.aien/verify.pub, .github/workflows/*);
#   3. git rebase origin/<base>; conflicts in .crumb files only are resolved with the base's copy;
#      any other conflicting file aborts the rebase;
#   4. recompile crumbs with the crumb tool pinned by the base branch (crumb.lock, else the aien-architecture pin in
#      .github/workflows/aien-verification.yml), commit "crumb: recompile after rebase onto main" when that changed
#      anything (only .crumb files may change), crumb verify;
#   5. git push --force-with-lease=<branch>:<old head> to the pull request's branch.
# A non-.crumb conflict (or a recompile that touches other files) adds the label needs-rebase and posts one comment
# per head sha. --dry-run does all local work and prints what it would do; it pushes, labels, comments and journals
# nothing.
#
# GitHub API budget: one `gh pr list` per repo (label filtered here: `gh pr list --label` returned nothing on
# 2026-10-18 while 12 labeled pull requests were open); per blocked pull request at most one `gh pr view` (comment
# de-duplication), one label call and one comment (plus one label create per repo, once ever). Pushes use git.
# One instance at a time (flock on $STATE/train.lock; a second one exits 0). Every decision is one JSON line in
# $STATE/train.jsonl: {utc, repo, pr, head, action, reason}.
# Exit: 0 run done (skips and refusals included), 2 usage or configuration error.
set -euo pipefail

STATE=${AIEN_STATE:-$HOME/.local/state/aien-local-ci}
CLONES=${AIEN_CLONES:-$HOME/workspace/pipeline/clones}
ARCH_CLONE=${AIEN_ARCH_CLONE:-$CLONES/aien-architecture}
OWNER=${AIEN_GH_OWNER:-aien-dev}
REPOS=${AIEN_REPOS:-aien-sovereign-core,omega,aienos,physics,aien-protocols,aegis-runtime,spark-rsi,aien-architecture,benchmarks,synapse,interplane}
GH=${GH:-gh}
GIT=${GIT:-git}
MERGE_LABEL="ready-to-merge"
BLOCK_LABEL="needs-rebase"
MIN_AGE=${AIEN_TRAIN_MIN_AGE:-600}
AI_LINE='> *This was generated by AI during triage.*'
MARK='aien-rebase-train head='

usage() { echo "usage: rebase-train.sh [--dry-run] [--repos a,b] [--pr N]" >&2; exit 2; }
die() { echo "rebase-train.sh: $*" >&2; exit 2; }

DRY=0 ONLY=""
while [[ $# -gt 0 ]]; do
  case "$1" in
    --dry-run) DRY=1; shift ;;
    --repos) [[ $# -ge 2 ]] || usage; REPOS=$2; shift 2 ;;
    --pr) [[ $# -ge 2 && $2 =~ ^[0-9]+$ ]] || usage; ONLY=$2; shift 2 ;;
    *) usage ;;
  esac
done
IFS=, read -r -a repo_list <<< "$REPOS"
[[ ${#repo_list[@]} -gt 0 ]] || die "no repositories named"
for r in "${repo_list[@]}"; do
  [[ $r =~ ^[A-Za-z0-9._-]+$ && $r != . && $r != .. ]] || die "bad repository name '$r'"
done
command -v jq >/dev/null || die "jq not found"
command -v flock >/dev/null || die "flock not found"
command -v make >/dev/null || die "make not found"
command -v "$GIT" >/dev/null || die "git ($GIT) not found"
command -v "$GH" >/dev/null || die "gh ($GH) not found"
[[ -d $CLONES ]] || die "clones directory $CLONES missing"

mkdir -p "$STATE"
JOURNAL=$STATE/train.jsonl
COMMENTED=$STATE/train-commented        # lines "<repo> <pr> <head>": a comment was posted for that head
LABELED=$STATE/train-labels             # lines "<repo>": the needs-rebase label exists there
TOOLS=$STATE/crumb-tools                # <pin>/crumb: crumb tools built from aien-architecture at <pin>
exec 9>>"$STATE/train.lock"
flock -n 9 || exit 0
WORK=$(mktemp -d "$STATE/.train.XXXXXX")
CLEAN=()   # "<clone>|<worktree>|<ref>" to remove on exit
GH_DEFER=$WORK/gh-deferred
# ghc ARGS...: every GitHub call goes through here. ~/.local/bin/gh (the shared rate-limit guard) exits 98 when it
# refuses (allowance reserved or rate-limit marker set): then this run makes no further GitHub call, and every
# journal line from then on carries deferred="gh guard exit 98: try next round". Never a retry loop, never a FAIL.
ghc() {
  local rc=0
  [[ -e $GH_DEFER ]] && return 98
  "$GH" "$@" || rc=$?
  [[ $rc != 98 ]] || : > "$GH_DEFER"
  return "$rc"
}
cleanup() {
  local e c w ref
  for e in "${CLEAN[@]}"; do
    IFS='|' read -r c w ref <<< "$e"
    [[ -n $w ]] && "$GIT" -C "$c" worktree remove --force "$w" >/dev/null 2>&1
    [[ -n $ref ]] && "$GIT" -C "$c" update-ref -d "$ref" >/dev/null 2>&1
    "$GIT" -C "$c" worktree prune >/dev/null 2>&1
  done
  rm -rf "$WORK"
}
trap cleanup EXIT

# journal REPO PR HEAD ACTION REASON: one JSON line (not in --dry-run) and one short line on stdout.
journal() {
  local p=""; [[ $DRY == 1 ]] && p="[dry-run] "
  echo "${p}$1#$2 ${3:0:8} $4: $5"
  [[ $DRY == 1 ]] && return 0
  local r=$5
  [[ ! -e $GH_DEFER ]] || r+=" (gh guard exit 98: try next round)"
  jq -nc --arg utc "$(date -u +%Y-%m-%dT%H:%M:%SZ)" --arg repo "$1" --arg pr "$2" --arg head "$3" \
    --arg action "$4" --arg reason "$r" '{utc: $utc, repo: $repo, pr: $pr, head: $head, action: $action, reason: $reason}' \
    >> "$JOURNAL"
}

# g DIR ARGS...: git in a worktree, never running hooks (the tree under test is not trusted).
g() { local d=$1; shift; "$GIT" -C "$d" -c core.hooksPath=/dev/null "$@"; }

is_crumb() { [[ $1 == .crumb || $1 == */.crumb ]]; }

# crumb_pin CLONE REF: the aien-architecture commit whose crumb tool the base branch pins (empty when none).
crumb_pin() {
  local p
  p=$("$GIT" -C "$1" show "$2:crumb.lock" 2>/dev/null | grep -oE '\b[0-9a-f]{40}\b' | head -n 1 || true)
  [[ -n $p ]] || p=$("$GIT" -C "$1" show "$2:.github/workflows/aien-verification.yml" 2>/dev/null \
    | grep -oE 'aien-architecture @ [0-9a-f]{40}' | head -n 1 | grep -oE '[0-9a-f]{40}' || true)
  echo "$p"
}

# crumb_tool PIN: path of the crumb binary built from aien-architecture at PIN (built once, cached). Same build as
# aien-verification.yml: make -C tools/crumb crumb.
crumb_tool() {
  local pin=$1 out=$TOOLS/$1/crumb src
  if [[ ! -x $out ]]; then
    [[ -d $ARCH_CLONE/.git ]] || return 1
    "$GIT" -C "$ARCH_CLONE" cat-file -e "$pin^{commit}" 2>/dev/null || "$GIT" -C "$ARCH_CLONE" fetch -q origin || return 1
    "$GIT" -C "$ARCH_CLONE" cat-file -e "$pin^{commit}" 2>/dev/null || return 1
    src=$WORK/crumb-src-$pin
    mkdir -p "$src"
    "$GIT" -C "$ARCH_CLONE" archive "$pin" tools/crumb | tar -x -C "$src" || return 1
    make -s -C "$src/tools/crumb" crumb >/dev/null || return 1
    mkdir -p "$TOOLS/$pin"
    cp "$src/tools/crumb/crumb" "$out.tmp" && mv "$out.tmp" "$out"
  fi
  echo "$out"
}

# slug REPO: canonical owner/name on GitHub (aien-dev/<repo> may redirect to aien-dev/<repo>-mv), only when the train
# is about to write (label, comment). Shares pipeline.sh's disk cache $STATE/slugs/<repo> (24 h; an older name is
# used when the refresh fails).
slug() {
  local f=$STATE/slugs/$1 s="" fresh re='^[A-Za-z0-9._-]+/[A-Za-z0-9._-]+$'
  [[ -f $f ]] && s=$(head -n 1 "$f")
  if [[ $s =~ $re ]] && (( $(date +%s) - $(stat -c %Y "$f") < ${AIEN_SLUG_TTL:-86400} )); then echo "$s"; return 0; fi
  if fresh=$(ghc api "repos/$OWNER/$1" --jq .full_name 2>/dev/null) && [[ $fresh =~ $re ]]; then
    mkdir -p "$STATE/slugs" && printf '%s\n' "$fresh" > "$f.tmp" && mv "$f.tmp" "$f"
    echo "$fresh"; return 0
  fi
  [[ $s =~ $re ]] && { echo "$s"; return 0; }
  return 1
}

declare -A LABEL_OK=()
# block REPO SLUG PR HEAD LABELS WHY FILES: label needs-rebase and post one comment for this head.
block() {
  local repo=$1 s=$2 num=$3 head=$4 labels=$5 why=$6 files=$7 body seen
  if [[ $DRY == 1 ]]; then
    journal "$repo" "$num" "$head" would-block "$why: $(paste -sd' ' <<< "$files")"; return 0
  fi
  journal "$repo" "$num" "$head" blocked "$why: $(paste -sd' ' <<< "$files")"
  if ! s=$(slug "$repo"); then journal "$repo" "$num" "$head" label-failed "cannot resolve GitHub slug"; return 0; fi
  if [[ ,$labels, != *",$BLOCK_LABEL,"* ]]; then
    if [[ -z ${LABEL_OK[$repo]:-} ]] && ! grep -qx "$repo" "$LABELED" 2>/dev/null; then
      if ghc label create "$BLOCK_LABEL" -R "$s" --color D93F0B \
           --description "The rebase train could not rebase this onto main by itself" >/dev/null 2>&1 \
         || ghc label list -R "$s" --search "$BLOCK_LABEL" --json name --jq '.[].name' 2>/dev/null | grep -qx "$BLOCK_LABEL"; then
        echo "$repo" >> "$LABELED"
      else
        journal "$repo" "$num" "$head" label-failed "cannot create label $BLOCK_LABEL"
      fi
    fi
    LABEL_OK[$repo]=1
    if ghc api -X POST "repos/$s/issues/$num/labels" -f "labels[]=$BLOCK_LABEL" >/dev/null 2>&1; then
      journal "$repo" "$num" "$head" labeled "$BLOCK_LABEL"
    else
      journal "$repo" "$num" "$head" label-failed "cannot add $BLOCK_LABEL"
    fi
  fi
  if grep -qx "$repo $num $head" "$COMMENTED" 2>/dev/null; then
    journal "$repo" "$num" "$head" comment-skipped "already commented on this head (state)"; return 0
  fi
  if ! seen=$(ghc pr view "$num" -R "$s" --json comments --jq "[.comments[].body | select(contains(\"$MARK$head\"))] | length"); then
    journal "$repo" "$num" "$head" comment-failed "cannot read comments"; return 0
  fi
  if [[ $seen != 0 ]]; then
    echo "$repo $num $head" >> "$COMMENTED"
    journal "$repo" "$num" "$head" comment-skipped "already commented on this head (GitHub)"; return 0
  fi
  body=$WORK/comment.md
  {
    echo "$AI_LINE"
    echo
    echo "The rebase train (\`tools/aien-local-ci/rebase-train.sh\`) could not move this pull request onto the latest"
    echo "\`main\` by itself: $why. It resolves only \`.crumb\` files (generated by the crumb compiler) on its own."
    echo
    echo "Files that need a person (or an agent) to resolve:"
    echo
    while IFS= read -r f; do [[ -n $f ]] && echo "- \`$f\`"; done <<< "$files"
    echo
    echo "Rebase the branch onto \`main\` by hand, resolve these files, and push. The \`$BLOCK_LABEL\` label was added;"
    echo "the train tries again on every run and removes the label once a rebase goes through."
    echo
    echo "<!-- $MARK$head -->"
  } > "$body"
  if ghc api -X POST "repos/$s/issues/$num/comments" -F "body=@$body" >/dev/null 2>&1; then
    echo "$repo $num $head" >> "$COMMENTED"
    journal "$repo" "$num" "$head" commented "conflict comment posted"
  else
    journal "$repo" "$num" "$head" comment-failed "cannot post comment"
  fi
}

# train_one REPO SLUG PR HEAD BRANCH BASE LABELS: one candidate, end to end.
train_one() {
  local repo=$1 s=$2 num=$3 head=$4 branch=$5 base=$6 labels=$7 clone=$CLONES/$1
  local ref=refs/aien-train/$3 wt=$WORK/$1-$3 age touched pin tool=""
  local unmerged other f n=0 changed="" recompiled=unchanged newhead out
  if ! "$GIT" -C "$clone" fetch -q origin "+pull/$num/head:$ref"; then
    journal "$repo" "$num" "$head" skipped "fetch of pull/$num/head failed"; return 0
  fi
  CLEAN+=("$clone||$ref")
  [[ $("$GIT" -C "$clone" rev-parse "$ref") == "$head" ]] || { journal "$repo" "$num" "$head" skipped "head moved while fetching"; return 0; }
  age=$(( $(date +%s) - $("$GIT" -C "$clone" show -s --format=%ct "$head") ))
  if (( age < MIN_AGE )); then
    journal "$repo" "$num" "$head" skipped "head commit is ${age}s old (< ${MIN_AGE}s): pushed recently"; return 0
  fi
  touched=$("$GIT" -C "$clone" diff --name-only "origin/$base...$head" -- .aien/verify.pub '.github/workflows/*' || echo "?diff failed")
  if [[ -n $touched ]]; then
    journal "$repo" "$num" "$head" skipped "touches trust surface, never rebased by the train: $(paste -sd' ' <<< "$touched")"; return 0
  fi
  pin=$(crumb_pin "$clone" "origin/$base")
  if [[ -n $pin ]] && ! tool=$(crumb_tool "$pin"); then
    journal "$repo" "$num" "$head" skipped "cannot build crumb tool at aien-architecture $pin"; return 0
  fi
  if [[ -z $pin ]] && "$GIT" -C "$clone" ls-tree -r --name-only "origin/$base" | grep -qE '(^|/)\.crumb$'; then
    journal "$repo" "$num" "$head" skipped "repo has .crumb files but origin/$base pins no crumb tool"; return 0
  fi
  if ! "$GIT" -C "$clone" worktree add -q --detach "$wt" "$head" 2>/dev/null; then
    journal "$repo" "$num" "$head" skipped "cannot create scratch worktree"; return 0
  fi
  CLEAN+=("$clone|$wt|")
  # Rebase; every stop must be .crumb-only conflicts (taken from the base side, "ours" during a rebase).
  g "$wt" rebase -q "origin/$base" >/dev/null 2>&1 || true
  while [[ -e $(g "$wt" rev-parse --git-path rebase-merge) || -e $(g "$wt" rev-parse --git-path rebase-apply) ]]; do
    (( ++n <= 500 )) || { g "$wt" rebase --abort >/dev/null 2>&1 || true; journal "$repo" "$num" "$head" skipped "rebase did not finish"; return 0; }
    unmerged=$(g "$wt" diff --name-only --diff-filter=U)
    if [[ -z $unmerged ]]; then
      if g "$wt" diff --cached --quiet; then GIT_EDITOR=true g "$wt" rebase --skip >/dev/null 2>&1 || true
      else GIT_EDITOR=true g "$wt" rebase --continue >/dev/null 2>&1 || true; fi
      continue
    fi
    other=""
    while IFS= read -r f; do is_crumb "$f" || other+="$f"$'\n'; done <<< "$unmerged"
    if [[ -n $other || -z $pin ]]; then
      g "$wt" rebase --abort >/dev/null 2>&1 || true
      if [[ -n $other ]]; then block "$repo" "$s" "$num" "$head" "$labels" "rebase onto origin/$base conflicts" "${other%$'\n'}"
      else journal "$repo" "$num" "$head" skipped "crumb conflict but no crumb tool pin"; fi
      return 0
    fi
    while IFS= read -r f; do
      if g "$wt" cat-file -e ":2:$f" 2>/dev/null; then g "$wt" checkout -q --ours -- "$f" && g "$wt" add -- "$f"
      else g "$wt" rm -q -- "$f"; fi
    done <<< "$unmerged"
    GIT_EDITOR=true g "$wt" rebase --continue >/dev/null 2>&1 || true
  done
  newhead=$(g "$wt" rev-parse HEAD)
  if ! g "$wt" merge-base --is-ancestor "origin/$base" HEAD; then
    journal "$repo" "$num" "$head" skipped "rebase failed before starting (head left as is)"; return 0
  fi
  # A pull request whose changes are already in the base would become empty (or crumb-only): never push that.
  other=""
  while IFS= read -r f; do [[ -z $f ]] || is_crumb "$f" || other+="$f"$'\n'; done \
    <<< "$(g "$wt" diff --name-only "origin/$base" HEAD)"
  if [[ -z $other ]]; then
    journal "$repo" "$num" "$head" skipped "nothing but .crumb files left after the rebase (changes already in origin/$base?)"
    return 0
  fi
  if [[ -n $pin ]]; then
    if ! out=$(cd "$wt" && "$tool" compile . 2>&1); then
      journal "$repo" "$num" "$head" skipped "crumb compile failed: $(tail -n 1 <<< "$out")"; return 0
    fi
    changed=$(g "$wt" status --porcelain=v1 --untracked-files=all | cut -c4-)
    other=""
    while IFS= read -r f; do [[ -z $f ]] || is_crumb "$f" || other+="$f"$'\n'; done <<< "$changed"
    if [[ -n $other ]]; then
      block "$repo" "$s" "$num" "$head" "$labels" "crumb recompile after the rebase changed files other than .crumb" "${other%$'\n'}"
      return 0
    fi
    if [[ -n $changed ]]; then
      g "$wt" add -A -- . && g "$wt" commit -q -m "crumb: recompile after rebase onto main" \
        -m "Generated by tools/aien-local-ci/rebase-train.sh with the crumb tool from aien-architecture @ $pin." \
        || { journal "$repo" "$num" "$head" skipped "crumb commit failed"; return 0; }
      newhead=$(g "$wt" rev-parse HEAD); recompiled=recompiled
    fi
    if ! (cd "$wt" && "$tool" verify . >/dev/null 2>&1); then
      journal "$repo" "$num" "$head" skipped "crumb verify fails after recompile (nothing pushed)"; return 0
    fi
  fi
  if [[ $newhead == "$head" ]]; then
    journal "$repo" "$num" "$head" skipped "rebase changed nothing"; return 0
  fi
  if [[ $DRY == 1 ]]; then
    journal "$repo" "$num" "$head" would-push "would rebase onto origin/$base + recompile crumbs + push $branch (local result ${newhead:0:8}, crumbs $recompiled)"
    return 0
  fi
  if g "$wt" push -q --force-with-lease="refs/heads/$branch:$head" origin "HEAD:refs/heads/$branch" >/dev/null 2>&1; then
    journal "$repo" "$num" "$head" pushed "rebased onto origin/$base, new head $newhead, crumbs $recompiled"
    if [[ ,$labels, == *",$BLOCK_LABEL,"* ]]; then
      if s=$(slug "$repo") && ghc api -X DELETE "repos/$s/issues/$num/labels/$BLOCK_LABEL" >/dev/null 2>&1; then
        journal "$repo" "$num" "$newhead" unlabeled "$BLOCK_LABEL removed after a clean rebase"
      fi
    fi
  else
    journal "$repo" "$num" "$head" push-failed "force-with-lease push refused or failed (branch moved?)"
  fi
}

for repo in "${repo_list[@]}"; do
  [[ -d $CLONES/$repo/.git ]] || continue
  s=$OWNER/$repo
  if ! "$GIT" -C "$CLONES/$repo" fetch -q origin; then
    journal "$repo" - - skipped "fetch of trusted clone failed"; continue
  fi
  if ! prs=$(ghc pr list -R "$s" --state open --limit 100 \
      --json number,headRefOid,headRefName,baseRefName,isDraft,isCrossRepository,mergeable,mergeStateStatus,labels \
      --jq '.[] | [.number, .headRefOid, .headRefName, .baseRefName, .isDraft, .isCrossRepository, .mergeable,
                   .mergeStateStatus, ([.labels[].name] | join(","))] | @tsv'); then
    journal "$repo" - - skipped "cannot list pull requests"; continue
  fi
  while IFS=$'\t' read -r num head branch base draft cross mergeable mstate labels; do
    [[ -n $num ]] || continue
    [[ -z $ONLY || $num == "$ONLY" ]] || continue
    [[ ,$labels, == *",$MERGE_LABEL,"* ]] || continue
    [[ $mergeable == CONFLICTING || $mstate == BEHIND ]] || continue
    if [[ ! $head =~ ^[0-9a-f]{40}$ ]]; then journal "$repo" "$num" "$head" skipped "bad head sha"; continue; fi
    if [[ ! $branch =~ ^[A-Za-z0-9._/-]+$ || $branch == *..* || ! $base =~ ^[A-Za-z0-9._/-]+$ || $base == *..* ]]; then
      journal "$repo" "$num" "$head" skipped "bad branch or base name"; continue
    fi
    if [[ $draft != false ]]; then journal "$repo" "$num" "$head" skipped "draft"; continue; fi
    if [[ $cross != false ]]; then journal "$repo" "$num" "$head" skipped "head is in a fork"; continue; fi
    train_one "$repo" "$s" "$num" "$head" "$branch" "$base" "$labels"
  done <<< "$prs"
done
exit 0
