#!/usr/bin/env python3
"""Unicode class table of om/flint/tok.om. GENERATOR ONLY, never an implementation dependency.

The encode pre_tokenizer of the pinned Flint tokenizer (tokenizers 0.23.2, Oniguruma through the
onig 6.5.3 crate) uses \\p{Lu} \\p{Ll} \\p{Lt} \\p{Lm} \\p{Lo} \\p{L} \\p{M} \\p{N} \\p{P} \\p{S}
and \\s. tok.om classifies every code point into one of 11 classes:
  a other (C*, Z* that is not White_Space, unassigned, surrogates), b Lu, c Ll, d Lt, e Lm, f Lo,
  g M (Mn Mc Me), h N (Nd Nl No), i P (Pc Pd Ps Pe Pi Pf Po), j S (Sm Sc Sk So),
  k White_Space (PropList; every such code point is Cc, Zs, Zl or Zp, so it has no other class)
and stores them as runs over 0 .. 1114111: a class letter, then the run length in decimal.

Usage: ucdgen.py UCD_DIR     prints the generated block of tok.om (from its marker line to its end
                             line); UCD_DIR holds UnicodeData.txt and PropList.txt of Unicode 16.0.0
                             (https://www.unicode.org/Public/16.0.0/ucd/), checked against UCD_PINS.
tokref.py imports runs() to write the same string from the referee's own regex engine.
"""
import hashlib
import os
import sys

NCP = 0x110000
UCD_VERSION = "16.0.0"
UCD_PINS = {
    "UnicodeData.txt": "ff58e5823bd095166564a006e47d111130813dcf8bf234ef79fa51a870edb48f",
    "PropList.txt": "53d614508e2a0b2305a8aa21cd60d993de9326cdf65993660dfcce4503548583",
}
# class letter -> the referee regex of that class (tokref.py) and its General Categories (here)
CLASSES = [
    ("b", r"\p{Lu}", ["Lu"]),
    ("c", r"\p{Ll}", ["Ll"]),
    ("d", r"\p{Lt}", ["Lt"]),
    ("e", r"\p{Lm}", ["Lm"]),
    ("f", r"\p{Lo}", ["Lo"]),
    ("g", r"\p{M}", ["Mn", "Mc", "Me"]),
    ("h", r"\p{N}", ["Nd", "Nl", "No"]),
    ("i", r"\p{P}", ["Pc", "Pd", "Ps", "Pe", "Pi", "Pf", "Po"]),
    ("j", r"\p{S}", ["Sm", "Sc", "Sk", "So"]),
    ("k", r"\s", None),
]
BEGIN = "note ======== unicode classes (generated by test/ucdgen.py from UCD %s; do not edit) ========" % UCD_VERSION
END = "note ======== end of generated unicode classes ========"


def runs(cls):
    """cls: bytearray of NCP class letters; the run string."""
    out = []
    s = 0
    for c in range(1, NCP + 1):
        if c == NCP or cls[c] != cls[s]:
            out.append("%c%d" % (cls[s], c - s))
            s = c
    return "".join(out)


def from_ucd(d):
    for name, pin in UCD_PINS.items():
        got = hashlib.sha256(open(os.path.join(d, name), "rb").read()).hexdigest()
        if got != pin:
            sys.exit("ucdgen: %s sha256 %s, pinned %s" % (name, got, pin))
    gc = {}
    rows = open(os.path.join(d, "UnicodeData.txt")).read().splitlines()
    i = 0
    while i < len(rows):
        f = rows[i].split(";")
        c = int(f[0], 16)
        e = c
        if f[1].endswith(", First>"):
            e = int(rows[i + 1].split(";")[0], 16)
            i += 1
        for x in range(c, e + 1):
            gc[x] = f[2]
        i += 1
    letter = {g: k for k, _, gs in CLASSES if gs for g in gs}
    cls = bytearray(b"a" * NCP)
    for c, g in gc.items():
        if g in letter:
            cls[c] = ord(letter[g])
    for row in open(os.path.join(d, "PropList.txt")):
        f = [x.strip() for x in row.split("#")[0].split(";")]
        if len(f) == 2 and f[1] == "White_Space":
            a, _, b = f[0].partition("..")
            for c in range(int(a, 16), int(b or a, 16) + 1):
                if cls[c] != ord("a"):
                    sys.exit("ucdgen: White_Space U+%04X has class %c" % (c, cls[c]))
                cls[c] = ord("k")
    return cls


def block(s):
    return "\n".join([
        BEGIN,
        "note ucd: the class of every code point 0 .. 1114111 as runs, each a class letter then its",
        "note length in decimal: a other, b Lu, c Ll, d Lt, e Lm, f Lo, g M, h N, i P, j S, k White_Space",
        'text ucd "%s"' % s,
        END,
    ])


if __name__ == "__main__":
    if len(sys.argv) != 2:
        sys.exit("usage: ucdgen.py UCD_DIR")
    print(block(runs(from_ucd(sys.argv[1]))))
